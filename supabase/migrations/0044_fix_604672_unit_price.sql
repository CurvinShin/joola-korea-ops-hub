-- =========================================================================
-- 604672(POWER FX Daydream 16mm, Global)의 소비자가가 NULL이라 딜러 주문 금액이
-- 0원으로 계산되던 문제 수정.
--
-- 0018에서 이 상품을 insert할 때 "on conflict (sku) do nothing"이었는데, 이미
-- 같은 SKU 행이 가격 없이 들어 있어서 insert가 건너뛰어졌다(demo_purchase_allowed
-- 만 별도 update로 맞춰졌다). 그래서 unit_price가 비어 있었다.
--
-- 299,000원은 0018의 원래 등록값이자 같은 계열 604680(Demo)과 같은 소비자가이며,
-- 기존 견적서의 공급가(176,700원 = 299,000 ÷ 1.1 × 0.65, 100원 반올림)와도 맞는다.
-- 가격이 이미 들어 있는 경우(NULL이 아닌 경우)는 건드리지 않는다.
-- =========================================================================

update products
set unit_price = 299000
where sku = '604672' and unit_price is null;
