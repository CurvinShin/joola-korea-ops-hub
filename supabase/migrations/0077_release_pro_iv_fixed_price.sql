-- PRO IV 12종의 고정 딜러가(176,600원)를 풀어서 다시 일반 계산(소비자가 기준 35% / 30% 딜러가)으로 되돌린다 (2026-11-06).
-- 확정 가격: 35% 딜러 153,000원, 30% 딜러 164,800원 (소비자가 259,000원, 부가세 미포함).
-- 고정 딜러가는 양말 12종(2,800 / 3,200)과 데모 전용 604680(95,100)만 남긴다.
-- 블랙프라이데이(11/2~11/15) 동안은 프로모션 가격이 우선이라 이 변경은 11/16부터 화면에 드러난다.
-- 이미 만들어진 주문의 단가는 바뀌지 않는다.

create table if not exists products_fixed_price_backup_20261106 as
select sku, name, unit_price, fixed_dealer_price
from products
where sku in ('300807','300810','300819','300822','300834','300837',
              '600015','600016','600147','600153','600159','600160');

update products set fixed_dealer_price = null
where sku in ('300807','300810','300819','300822','300834','300837',
              '600015','600016','600147','600153','600159','600160');

-- 검산: 고정가가 남은 제품이 양말 12종 + 604680 = 13건이면 정상
