-- =========================================================================
-- 용어 정리: SKU vs 상품코드
--
--   SKU     = 우리(JOOLA Korea) 고유 번호. 이지어드민 상품명 맨 앞 5~6자리 숫자.
--             products.sku (기존 컬럼, 이름은 그대로).
--   상품코드 = 우리 상품을 이지어드민(3PL)에 등록할 때 이지어드민이 부여한 코드(5자리,
--             앞자리 0 포함 가능, 예: 06867). products.ezadmin_code (이 파일에서 추가).
--
-- 1) products.ezadmin_code 컬럼을 추가한다 (문자열 — 앞자리 0 보존).
-- 2) inventory_status 뷰에 ezadmin_code를 덧붙인다 (재고 화면·검색·복사에서 사용).
-- 3) 2026-10-22 현재고조회 파일(615건)로 이미 등록된 제품의 상품코드를 채운다.
--    (SKU가 같은 제품에만 채우고, 이미 값이 있으면 건드리지 않는다.)
--
-- 이후에는 "재고 최신화"에 현재고조회 파일을 올릴 때마다 상품코드가 자동으로 맞춰진다.
-- 추가만 하는 SQL이라 운영 DB에서 먼저 실행해도 안전하다 (기존 화면은 그대로 동작).
-- =========================================================================

alter table products add column if not exists ezadmin_code text;

comment on column products.ezadmin_code is
  '이지어드민(3PL)에 상품을 등록할 때 발생한 상품코드 (5자리 문자열, 앞자리 0 포함 가능). 우리 고유 번호는 sku.';

create index if not exists products_ezadmin_code_idx on products (ezadmin_code);

-- 0019의 정의에 ezadmin_code 한 줄만 마지막에 덧붙인 것 (뷰는 열을 맨 끝에만 추가할 수 있다).
create or replace view inventory_status as
  select
    p.id as product_id,
    p.sku,
    p.name,
    p.category,
    p.discontinued,
    coalesce(i.current_stock, 0) as current_stock,
    coalesce(i.reserved_stock, 0) as reserved_stock,
    coalesce(i.current_stock, 0) - coalesce(i.reserved_stock, 0) as available_stock,
    coalesce(i.incoming_qty, 0) as incoming_qty,
    i.eta,
    coalesce(i.low_stock_threshold, 10) as low_stock_threshold,
    (coalesce(i.current_stock, 0) - coalesce(i.reserved_stock, 0)) <= coalesce(i.low_stock_threshold, 10) as is_low_stock,
    p.image_url,
    p.product_type,
    p.fixed_dealer_price,
    p.subcategory,
    p.demo_purchase_allowed,
    p.new_arrival_batch,
    p.ezadmin_code
  from products p
  left join inventory i on i.product_id = p.id;

