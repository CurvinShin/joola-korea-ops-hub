alter table purchase_orders
  add column if not exists po_kind text,
  add column if not exists closed boolean not null default false,
  add column if not exists source_folder text,
  add column if not exists item_count integer not null default 0,
  add column if not exists total_qty integer not null default 0;

create table if not exists overseas_po_items (
  id uuid primary key default gen_random_uuid(),
  po_id uuid not null references purchase_orders (id) on delete cascade,
  line_no integer not null,
  sku text not null,
  item_name text,
  qty integer not null default 0
);
create index if not exists overseas_po_items_po_idx on overseas_po_items (po_id);
create index if not exists overseas_po_items_sku_idx on overseas_po_items (sku);

create table if not exists overseas_po_shipments (
  id uuid primary key default gen_random_uuid(),
  po_id uuid not null references purchase_orders (id) on delete cascade,
  ship_date date,
  tracking_no text,
  carrier text,
  doc_name text,
  created_at timestamptz not null default now()
);
create index if not exists overseas_po_shipments_po_idx on overseas_po_shipments (po_id);

alter table overseas_po_items enable row level security;
alter table overseas_po_shipments enable row level security;

drop policy if exists overseas_po_items_select on overseas_po_items;
drop policy if exists overseas_po_items_insert on overseas_po_items;
drop policy if exists overseas_po_items_update on overseas_po_items;
drop policy if exists overseas_po_items_delete on overseas_po_items;
create policy overseas_po_items_select on overseas_po_items for select using (is_staff());
create policy overseas_po_items_insert on overseas_po_items for insert with check (can_write());
create policy overseas_po_items_update on overseas_po_items for update using (can_write()) with check (can_write());
create policy overseas_po_items_delete on overseas_po_items for delete using (can_write());

drop policy if exists overseas_po_shipments_select on overseas_po_shipments;
drop policy if exists overseas_po_shipments_insert on overseas_po_shipments;
drop policy if exists overseas_po_shipments_update on overseas_po_shipments;
drop policy if exists overseas_po_shipments_delete on overseas_po_shipments;
create policy overseas_po_shipments_select on overseas_po_shipments for select using (is_staff());
create policy overseas_po_shipments_insert on overseas_po_shipments for insert with check (can_write());
create policy overseas_po_shipments_update on overseas_po_shipments for update using (can_write()) with check (can_write());
create policy overseas_po_shipments_delete on overseas_po_shipments for delete using (can_write());

